/**
 * Цвет нутриента — единственный источник в коде.
 *
 * До этого модуля цвет был объявлен в четырёх местах по-разному: на дашборде
 * жиры были `#f59e0b`, в сводке трекера `bg-yellow-500` (то есть `#eab308`), а
 * в подытоге приёма пищи и в окне записи цвета не было вовсе. Разные цвета
 * одного нутриента на двух экранах — доказательство, что общего решения о них
 * никто не принимал.
 *
 * Сами значения живут в дизайн-токенах (`packages/design-tokens`, роли
 * `color.macro.*`), здесь — ссылки на них в виде CSS-переменных. Переменная
 * годится и для `stroke` в SVG, и для `backgroundColor`, и сама переключается
 * между светлой и тёмной темой; класс Tailwind (`bg-protein`) — та же роль для
 * разметки. Пара «класс + hex» больше не разъедется: оба смотрят в один токен.
 *
 * Два цвета на нутриент: заливка (полосы, сегменты) и текст (подпись рядом с
 * числом). Текстовый темнее — подпись обязана держать контраст 4.5:1, заливка
 * полосы только 3:1; сборка токенов проверяет оба.
 *
 * Здесь нет калорий. Цвет опознаёт нутриент, и калории как сумму нутриентов
 * опознавать нечем: раньше они красились оценкой выполнения нормы, из-за чего
 * цвет работал двумя работами сразу.
 */
import { color } from '@burcev/design-tokens'

export const MACRO_KEYS = ['protein', 'fat', 'carbs'] as const

export type MacroKey = (typeof MACRO_KEYS)[number]

/** Заливка: полосы, сегменты кольца, точки. */
export const MACRO_COLORS: Record<MacroKey, string> = {
    protein: color.protein,
    fat: color.fat,
    carbs: color.carbs,
}

/** Подпись нутриента текстом. */
export const MACRO_TEXT_COLORS: Record<MacroKey, string> = {
    protein: color['protein-fg'],
    fat: color['fat-fg'],
    carbs: color['carbs-fg'],
}

/** Цвет нутриента. Обращение по ключу, чтобы опечатка не давала `undefined`. */
export function macroColor(key: MacroKey): string {
    return MACRO_COLORS[key]
}
