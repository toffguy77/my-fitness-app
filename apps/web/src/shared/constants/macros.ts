/**
 * Цвет нутриента — единственный источник.
 *
 * До этого модуля цвет был объявлен в четырёх местах по-разному: на дашборде
 * жиры были `#f59e0b`, в сводке трекера `bg-yellow-500` (то есть `#eab308`), а
 * в подытоге приёма пищи и в окне записи цвета не было вовсе. Разные цвета
 * одного нутриента на двух экранах — доказательство, что общего решения о них
 * никто не принимал.
 *
 * Значения шестнадцатеричные, а не классы Tailwind, потому что кольцу нужен
 * `stroke` в SVG. Пара «класс + hex» разъезжается при первой правке одного из
 * двух — именно так и получилось нынешнее расхождение.
 *
 * Здесь нет калорий. Цвет опознаёт нутриент, и калории как сумму нутриентов
 * опознавать нечем: раньше они красились оценкой выполнения нормы, из-за чего
 * цвет работал двумя работами сразу.
 */

export const MACRO_KEYS = ['protein', 'fat', 'carbs'] as const

export type MacroKey = (typeof MACRO_KEYS)[number]

export const MACRO_COLORS: Record<MacroKey, string> = {
    protein: '#3b82f6',
    fat: '#f59e0b',
    carbs: '#22c55e',
}

/** Цвет нутриента. Обращение по ключу, чтобы опечатка не давала `undefined`. */
export function macroColor(key: MacroKey): string {
    return MACRO_COLORS[key]
}
