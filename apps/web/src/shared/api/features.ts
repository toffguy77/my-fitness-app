/**
 * Способности этого развёртывания, по мнению самого API.
 *
 * Строятся не из переменной сборки, а из живого `/ready`: способность выводится
 * на бэкенде из наличия учётных данных (`config.Features`), и второй источник
 * правды здесь молча разошёлся бы с первым.
 *
 * Пустой объект при любом отказе — не перестраховка, а единственный честный
 * вариант: обещание, которое некому подтвердить, не даётся. Страница при этом
 * открывается — она и без тезисов о способностях работает.
 *
 * Живёт в shared, потому что спрашивают два экрана: посадочная и тарифы. Две
 * копии этой функции разошлись бы ровно в том, что считать отказом.
 */

const API_URL = process.env.INTERNAL_API_URL || 'http://api:4000'

/**
 * Сколько ждём `/ready`, прежде чем открыть страницу без утверждений о
 * способностях. Тот же приём, что у ARTICLE_FETCH_TIMEOUT_MS в
 * apps/web/src/app/sitemap.ts — граница на ожидание, а не зависание.
 *
 * Посадочная динамическая (корневой layout зовёт headers() ради nonce), значит
 * рендерится заново на каждый заход: не ограничь мы `/ready` сроком, зависший
 * ответ (сеть есть, ответа нет — ровно как в инциденте с DNS) задержал бы
 * каждого посетителя, а не только сборку.
 *
 * Экспортирована ради теста — он сверяется с реальным значением, а не дублирует
 * магическое число рядом.
 */
export const READY_TIMEOUT_MS = 2000

export async function enabledFeatures(): Promise<Record<string, boolean>> {
    try {
        const res = await fetch(`${API_URL}/ready`, {
            next: { revalidate: 60 },
            signal: AbortSignal.timeout(READY_TIMEOUT_MS),
        })
        if (!res.ok) return {}
        const data = await res.json()
        return data?.features || {}
    } catch {
        return {}
    }
}
