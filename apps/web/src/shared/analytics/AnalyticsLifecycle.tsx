'use client'

import { useEffect } from 'react'
import { startAnalytics } from './client'

/**
 * Включает отправку накопленных событий при уходе со страницы.
 *
 * Смонтирован в корневом макете, а не на отдельных экранах. До этого
 * `startAnalytics()` звали только `TrackView` и `TrackScrollDepth`, а они стоят
 * на посадочной и в гостевом мастере — то есть на всех страницах вошедшего
 * человека обработчики `pagehide`, `beforeunload` и `visibilitychange` не
 * регистрировались вовсе.
 *
 * Последствие: событие, попавшее в очередь на дневнике питания или в чате,
 * ждало истечения интервала в десять секунд, и переход, закрытие вкладки или
 * уход в фон уносили его молча. Требование спеки — отправлять «при уходе со
 * страницы» — на этих страницах не выполнялось.
 *
 * Вызов идемпотентен: `startAnalytics` защищён собственным флагом, поэтому
 * лишним он нигде не будет.
 */
export function AnalyticsLifecycle() {
    useEffect(() => {
        startAnalytics()
    }, [])

    return null
}
