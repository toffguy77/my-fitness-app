import { t } from '../index'

/**
 * Вес, рост, пол, возраст и фотографии прогресса — сведения о состоянии
 * здоровья, то есть специальная категория персональных данных. Согласие на них
 * должно называть, на что именно человек соглашается: «согласен на обработку
 * персональных данных» не является ни конкретным, ни осознанным.
 *
 * Формулировку легко упростить обратно — она длинная и мешает вёрстке. Поэтому
 * здесь стоит проверка, а не только договорённость.
 */
describe('Тексты согласий называют, на что человек соглашается', () => {
    // Возраст спрашивают датой рождения, поэтому подходит любое из двух слов:
    // проверяется, что параметр назван, а не какой именно формулировкой.
    const collected = [/вес/, /рост/, /пол/, /возраст|дат[аы] рождения/]

    it('гостевой онбординг перечисляет собираемые параметры', () => {
        const text = t('onboarding.guest.consent').toLowerCase()

        for (const item of collected) {
            expect(text).toMatch(item)
        }
        expect(text).toContain('здоров')
    })

    it('регистрация тоже упоминает сведения о здоровье', () => {
        const text = t('auth.consent.personalData').toLowerCase()

        expect(text).toContain('здоров')
        for (const item of collected) {
            expect(text).toMatch(item)
        }
    })

    // Согласие на связь — отдельное разрешение, а не приложение к первому.
    // Объединённое «на всё сразу» не позволяет сохранить расчёт, отказавшись
    // от писем.
    it('согласие на письмо отдельное и говорит про отказ', () => {
        const text = t('onboarding.guest.reminder').toLowerCase()

        expect(text).toContain('письм')
        expect(text).toMatch(/отказ|отпис/)
        // И не тянет за собой обработку данных: это другое разрешение.
        expect(text).not.toContain('обработку персональных данных')
    })
})

/**
 * Виджет поддержки до регистрации собирает не то же самое, что онбординг —
 * только то, что человек ввёл (email), и текст самого разговора; ни веса, ни
 * роста, ни пола, ни даты рождения. Требовать от него слова «здоровье» было
 * бы неправдой, поэтому у него свой набор условий, а не copy-paste блока
 * выше — но тот же принцип: формулировку легко упростить обратно, и это
 * должно стать красным тестом, а не незамеченной правкой.
 */
describe('Согласия виджета поддержки называют предмет и не сливаются в одно', () => {
    it('согласие на обработку называет, что именно обрабатывается', () => {
        const text = t('supportWidget.consentData').toLowerCase()

        expect(text).toMatch(/данн/)
        expect(text).toMatch(/разговор/)
    })

    // Согласие на связь — отдельное разрешение. Слитые в одно, они превращают
    // «ответьте мне» в «пишите что хотите»: сначала на его собственный текст
    // (не совпадает с согласием на обработку), затем на то, что оно само не
    // выдаёт себя за согласие на обработку.
    it('согласие на связь — отдельное от согласия на обработку данных', () => {
        const data = t('supportWidget.consentData').toLowerCase()
        const contact = t('supportWidget.consentContact').toLowerCase()

        expect(contact).not.toBe(data)
        expect(contact).not.toContain('обработ')
    })
})
