package support

import (
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// Префикс обязан совпадать побайтово во всех каналах: иначе веб обнуляет кэш,
// и каждый вопрос начинает стоить полную цену. Это не оптимизация, а условие,
// при котором дневной потолок вообще имеет смысл.
//
// cachedPrefix сегодня не принимает канал — buildPrefix собирается только из
// базы знаний. Тест существует не потому, что здесь легко ошибиться сейчас, а
// потому, что "положить канал в промпт" — соблазн, который возникнет ровно
// тогда, когда ответ начнёт зависеть от канала, и тест обязан покраснеть
// в этот момент, а не молчать.
func TestCachedPrefixIsIdenticalAcrossChannels(t *testing.T) {
	svc, _, _ := setupSupport(t, &fakeAnswerer{})

	forTelegram, err := svc.cachedPrefix()
	require.NoError(t, err)
	forWeb, err := svc.cachedPrefix()
	require.NoError(t, err)

	// Проверка на пустом префиксе истинна вырожденно: NotContains(...) проходит
	// на "" при любом аргументе. Без этой строки тест не заметил бы, если
	// buildPrefix вдруг начал возвращать пустую строку.
	require.NotEmpty(t, forWeb, "префикс не должен быть пустым — иначе проверки ниже ничего не значат")

	assert.Equal(t, forTelegram, forWeb)

	// Ни канала, ни времени, ни идентификатора разговора в префиксе быть не
	// должно — каждое из них делает его уникальным на запрос.
	//
	// Год ("2006" в Go-формате) не годится сам по себе: база знаний законно
	// упоминает даты в примерах ("7 марта 2026"), и проверка на голый год
	// красила бы тест ложно. Секунда до наносекунды в реальном таймстампе в
	// прозе не встретится никогда, а свойство "времени в префиксе нет" она
	// проверяет так же надёжно.
	assert.NotContains(t, forWeb, ChannelWeb)
	assert.NotContains(t, forWeb, ChannelTelegram)
	assert.NotContains(t, forWeb, time.Now().Format("15:04:05.000000000"))
}
