package support

import "testing"

// Просьба позвать человека должна ловиться, а разговор о поддержке — нет.
//
// Список подстрок ловил «поддержк» в вопросе «какая поддержка форматов у фото?»
// и передавал обращение человеку: спросили про форматы, получили ожидание
// оператора. Явная команда и кнопка выражают намерение; угадывание осталось
// запасным путём и требует целого оборота.
func TestWantsHuman(t *testing.T) {
	for text, want := range map[string]bool{
		"/human":                            true,
		"/human нужна помощь":               true,
		"позовите человека":                 true,
		"позови оператора":                  true,
		"соедините с оператором":            true,
		"нужен живой человек":               true,
		"хочу человека":                     true,
		"можно менеджера":                   true,
		"Оператор?":                         true,
		"какая поддержка форматов у фото?":  false,
		"вы поддерживаете HEIC?":            false,
		"человеку свойственно ошибаться":    false,
		"как связаться с куратором в чате?": false,
		"поддержка приложения на телефоне":  false,
		"": false,
	} {
		if got := wantsHuman(text); got != want {
			t.Errorf("wantsHuman(%q) = %v, ожидалось %v", text, got, want)
		}
	}
}
