-- ВНИМАНИЕ: долгая блокировка. ALTER TABLE ... ADD COLUMN ... GENERATED ...
-- STORED переписывает таблицу целиком под ACCESS EXCLUSIVE. На трёх миллионах
-- строк замерено: 32 с на перезапись и 20 с на индекс, около 52 с суммарно, в
-- течение которых поиск еды не отвечает. Мигратор выполняет каждую миграцию в
-- одной транзакции, поэтому CONCURRENTLY недоступно, а разбить на шаги нельзя.
--
-- Если 52 с простоя поиска не годятся, эти же операторы можно выполнить
-- заранее вручную: миграция увидит колонку и индекс на месте (IF NOT EXISTS) и
-- запишется применённой, ничего не делая.
--
-- Зачем.
--
-- Поиск искал по выражению, и это выражение вычислялось дважды на каждую
-- отобранную строку: в ts_rank и в ORDER BY. Индекс закрывал только WHERE.
-- Пока запрос узкий, это незаметно; на широком слове — а в поиске вводят
-- именно широкие, «молоко», «хлеб», «творог» — ранжировать приходится десятки
-- тысяч строк, и пересчёт становится всей стоимостью запроса.
--
-- Замерено на трёх миллионах строк:
--
--   «творог»           1302 мс -> 168 мс
--   «хлеб ржаной»      1245 мс -> 320 мс
--   «молоко нежирный»    20 мс ->  20 мс   (узкий запрос, разницы нет)
--
-- Выражение колонки дословно совпадает с тем, что было в запросе, поэтому
-- ранги и порядок выдачи не меняются.
--
-- Таблица вырастает с 539 МБ до 1106 МБ; старый индекс на 172 МБ уходит,
-- так что чистый прирост около 400 МБ.

ALTER TABLE food_items
  ADD COLUMN IF NOT EXISTS search_vector tsvector
  GENERATED ALWAYS AS (
    to_tsvector('russian', COALESCE(name, '') || ' ' || COALESCE(brand, ''))
  ) STORED;

CREATE INDEX IF NOT EXISTS idx_food_items_search
  ON food_items USING gin (search_vector);

-- Прежний индекс по тому же выражению больше никем не читается.
DROP INDEX IF EXISTS idx_food_items_name_brand_fts;
