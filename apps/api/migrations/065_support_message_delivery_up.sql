-- Отметка о доставке ответа оператора.
--
-- Ответ оператора записывался до попытки отправки и оставался в переписке
-- независимо от её исхода. Когда Telegram отказывал — отозванный токен, нет
-- маршрута в IPv6, человек заблокировал бота — оператор видел «не удалось
-- отправить», а следующий оператор, открыв ту же переписку, видел обычное
-- сообщение и считал, что человеку ответили.
--
-- Колонка допускает NULL намеренно: у прежних сообщений исхода отправки не
-- знает никто, и проставлять им доставку значило бы выдумать то, чего не
-- проверяли.
ALTER TABLE support_messages ADD COLUMN delivered_at TIMESTAMPTZ;

COMMENT ON COLUMN support_messages.delivered_at IS
    'Когда Telegram принял сообщение. NULL у входящих, у сообщений до этой миграции и у неотправленного.';
