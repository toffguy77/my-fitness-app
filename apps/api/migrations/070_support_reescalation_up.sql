-- Отметка о повторном поднятии обращения.
--
-- Работа поднимает обращение на суперадминов, если куратор не ответил дольше
-- порога. Без этой отметки она звала бы их на каждом проходе: очередь, которая
-- кричит каждые пять минут, — это очередь, которую перестают читать.
--
-- Отдельной миграцией, а не правкой 069: та уже применена на тестовых стендах,
-- и править применённое — та самая дисциплина, нарушение которой в этом проекте
-- уже приводило к расхождению схемы.
ALTER TABLE support_conversations
  ADD COLUMN IF NOT EXISTS reescalated_at TIMESTAMPTZ;

COMMENT ON COLUMN support_conversations.reescalated_at IS 'Когда обращение подняли на суперадминов из-за молчания куратора';
