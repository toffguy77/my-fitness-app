-- Откуда взялся адрес ожидающего входа через провайдера.
--
-- Аккаунт через провайдера теперь создаётся только после согласий, то есть на
-- шаге позже того, где адрес стал известен. Адрес, который сообщил провайдер,
-- подтверждён им; адрес, который человек ввёл сам (VK его не отдаёт), — нет, и
-- такой аккаунт начинается неподтверждённым. Шагу согласий это надо знать, а
-- строка попытки различия не хранила.
--
-- По умолчанию false: строка без отметки считается введённой вручную — то
-- есть неподтверждённой, а не наоборот.
ALTER TABLE oauth_pending_links
  ADD COLUMN IF NOT EXISTS email_from_provider BOOLEAN NOT NULL DEFAULT false;
