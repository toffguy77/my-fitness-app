-- Индекс для подзапроса «последний разговор заявки» в очереди кураторов.
--
-- Service.Queue находит разговор каждой заявки коррелированным подзапросом:
-- SELECT ... FROM support_conversations WHERE lead_id = l.id ORDER BY
-- last_message_at DESC LIMIT 1 — по одному разу на строку, которую отдаст
-- страница. lead_id никогда не индексировался: idx_support_conversations_last_message
-- (миграция 052) покрывает только last_message_at, а внешние ключи Postgres
-- сам по себе не индексирует. Каждый такой подзапрос был последовательным
-- сканированием всей таблицы.
--
-- На сегодняшних объёмах это незаметно. Заметно станет раньше, чем кажется:
-- include_handled=true не укорачивает список, значит большие сдвиги достижимы
-- обычной прокруткой, а не только злым умыслом. Замеры на 50 000 заявок и
-- 20 000 переписок: сдвиг 40 000 без индекса — 34,8 с на один запрос; с этим
-- индексом — 7 мс.
CREATE INDEX IF NOT EXISTS idx_support_conversations_lead_recency
  ON support_conversations(lead_id, last_message_at DESC);
