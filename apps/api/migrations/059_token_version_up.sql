-- Отзыв refresh-токена закрывает будущее, но не настоящее: уже выпущенный
-- access-токен живёт ещё до пятнадцати минут и всё это время работает. После
-- смены пароля это ровно те пятнадцать минут, которые человек и пытался
-- отобрать у того, кто увёл его сессию.
--
-- Версия в записи пользователя попадает в токен и сверяется на каждом запросе.
-- Инкремент делает все ранее выпущенные токены недействительными сразу.
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;
