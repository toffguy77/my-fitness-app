-- Куда смотреть, когда придёт время убирать файлы стёртого пользователя.
--
-- Стирание обезличивает беседы в той же транзакции, поэтому после неё связь
-- «пользователь → его беседы» уже потеряна. А ключ вложения чата выглядит как
-- chat/{беседа}/{пользователь}/{файл} — идентификатор пользователя стоит не в
-- начале, и одним префиксом такие объекты не выбрать.
--
-- Значит, список префиксов надо посчитать до транзакции и сохранить. Иначе
-- повторная попытка после сбоя хранилища искала бы по связям, которых больше
-- нет, ничего не находила и записывала успех.
--
-- Формат: {"имя-бакета": ["префикс/", ...]}.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS pending_file_prefixes JSONB;

COMMENT ON COLUMN users.pending_file_prefixes IS
    'Префиксы объектов S3, подлежащих удалению после стирания аккаунта, по бакетам. NULL — удалять нечего или всё уже удалено.';
