-- ============================================================================
-- Миграция 084: у права на куратора появляется срок
-- ============================================================================
--
-- Работа с куратором становится платной услугой. Признаком права остаётся
-- активная связь в этой таблице — отдельная сущность подписки не заводится,
-- потому что два независимых признака права расходятся, и тогда непонятно,
-- какой из них правдив. Продление должно сохранять того же куратора и переписку
-- с ним, а новая строка на каждую оплату рвала бы историю работы.
--
-- Колонка — дата без времени и без зоны: администратор вводит именно дату, а
-- «последний оплаченный день» не имеет времени суток. Хранимая метка времени
-- создавала бы иллюзию точности, которой нет. Момент прекращения считается по
-- московскому времени; пояс объявлен в публичной оферте, иначе он неизвестен
-- тому, кто заплатил.
--
-- NULL означает бессрочное право. Все существующие связи получают NULL, то есть
-- до разового перевода живых клиентов в бесплатные никто ничего не теряет, а
-- служебные учётные записи (`*@burcev.test`, `e2e-*@burcev.team`) остаются
-- бессрочными навсегда — без этого набор сквозных проверок упёрся бы в
-- собственный платный доступ.

ALTER TABLE curator_client_relationships
    ADD COLUMN IF NOT EXISTS access_expires_at date;

COMMENT ON COLUMN curator_client_relationships.access_expires_at IS
    'Последний день действия права на работу с куратором, по московскому времени. NULL — бессрочно.';

-- Частичный индекс обслуживает два запроса, у которых нет других читателей:
-- задачу прекращения права и проверку расхождения, ищущую активные связи с
-- датой в прошлом. Оба смотрят только на срочные активные связи, и их доля от
-- таблицы со временем становится меньше.
CREATE INDEX IF NOT EXISTS idx_curator_client_access_expiry
    ON curator_client_relationships (access_expires_at)
    WHERE status = 'active' AND access_expires_at IS NOT NULL;
