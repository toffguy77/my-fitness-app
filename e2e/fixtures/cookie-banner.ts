import { expect, type Page } from '@playwright/test'

/**
 * Ответить на полосу про аналитические cookie так, как это делает человек.
 *
 * Виджет помощи не показывается, пока вопрос про cookie без ответа
 * (SupportWidget.tsx): на узком экране полоса и кнопка виджета — оба элемента
 * первого захода, и вдвоём они перекрывали кнопку «Далее» в гостевом мастере.
 * Поэтому у гостя виджета нет до ответа, и проверка, которой виджет нужен,
 * обязана сперва ответить.
 *
 * Ответ ставится кликом по настоящей кнопке, а не записью в localStorage:
 * запись прошла бы мимо самой полосы, и переименование ключа или поломка
 * обработчика остались бы незамеченными — проверки продолжали бы видеть
 * виджет, которого у живого посетителя уже не было бы.
 *
 * По умолчанию — «Отказаться»: счётчик в прогонах не нужен, и это тот же
 * выбор, который в спорном случае делают за посетителя.
 */
export async function answerCookieBanner(page: Page, choice: 'accept' | 'decline' = 'decline') {
    const banner = page.getByLabel('Аналитические cookie')
    await expect(banner).toBeVisible({ timeout: 15000 })
    await banner.getByRole('button', { name: choice === 'accept' ? 'Разрешить' : 'Отказаться' }).click()
    await expect(banner).toBeHidden()
}
