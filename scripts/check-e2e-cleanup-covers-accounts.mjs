#!/usr/bin/env node
/**
 * Каждая учётная запись, под которой ходит E2E, обязана попадать в зачистку.
 *
 * Требование владельца продукта к прогону на рабочем сервере звучит так:
 * после прогона — неважно, чем он кончился — прод должен остаться в том же
 * состоянии, что и до него. Держится это на `scripts/e2e-db-snapshot.sh`:
 * он записывает адреса учёток в слепок, а `scripts/e2e-db-cleanup.sh` потом
 * удаляет по слепку всё, что на них ссылается.
 *
 * Слабое место — не код, а список. Набор учёток объявлен в
 * `e2e/fixtures/test-accounts.ts` (их пять: client, curator, admin, плюс
 * второй куратор для проверок чужого доступа и отдельная учётка для смены
 * пароля, которая рвёт все сессии). Слепок же перечисляет имена переменных
 * у себя, своей строкой. Два списка, которые обязаны совпадать, и ничто их
 * не сверяло: учётка, добавленная в фикстуру и забытая в слепке, отработает
 * прогон и останется на проде — вместе со всем, что за ней тянется. Молча:
 * тесты зелёные, зачистка отчитывается об успехе, расхождения никто не видит,
 * потому что никто про эту учётку и не спрашивал.
 *
 * Ровно так этот скрипт и появился: на момент написания слепок знал три
 * адреса из пяти.
 *
 * Проверка: каждое имя вида E2E_*_EMAIL из фикстуры обязано встречаться в
 * списке переменных слепка. Обратное неверно намеренно — слепок вправе
 * знать адрес, которого в фикстуре нет (скажем, оставшийся от прошлого
 * набора): лишняя цель зачистки прод не пачкает, недостающая — пачкает.
 *
 * Запуск: node scripts/check-e2e-cleanup-covers-accounts.mjs
 */
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = process.env.CHECK_ROOT ?? join(dirname(fileURLToPath(import.meta.url)), '..')
const FIXTURE = join(ROOT, 'e2e/fixtures/test-accounts.ts')
const SNAPSHOT = join(ROOT, 'scripts/e2e-db-snapshot.sh')

function read(path, what) {
    try {
        return readFileSync(path, 'utf8')
    } catch {
        console.error(`не нашёл ${what}: ${path}`)
        process.exit(1)
    }
}

const fixture = read(FIXTURE, 'фикстуру учётных записей')
const snapshot = read(SNAPSHOT, 'скрипт слепка')

// Имена переменных берём из самой фикстуры, а не из отдельного перечня:
// перечень — это третий список, который точно так же разошёлся бы с двумя
// первыми.
const declared = [...fixture.matchAll(/['"](E2E_[A-Z0-9_]*_EMAIL)['"]/g)].map((m) => m[1])
const unique = [...new Set(declared)]

// Пол: фикстура без единой учётки означает, что регулярка перестала
// совпадать — например, фикстуру переписали на другой способ объявления.
// Без этой проверки такой скрипт «проходит», не проверив ничего.
if (unique.length === 0) {
    console.error(
        `В ${FIXTURE} не нашлось ни одной переменной вида E2E_*_EMAIL.\n` +
            'Либо фикстуру переписали, либо она пуста — в обоих случаях этот\n' +
            'сторож ничего не сторожит и молчать не должен.',
    )
    process.exit(1)
}

// Список слепка — строка перечисления переменных, а не весь файл: имя,
// упомянутое в комментарии или в примере использования, зачистку не делает.
const listing = snapshot.match(/for\s+var\s+in\s+([^\n;]+)/)
if (!listing) {
    console.error(
        `В ${SNAPSHOT} не нашёлся перечень переменных ("for var in ...").\n` +
            'Скрипт слепка переписан — сверять стало не с чем.',
    )
    process.exit(1)
}
const covered = new Set(listing[1].split(/\s+/).filter(Boolean))

const missing = unique.filter((name) => !covered.has(name))

if (missing.length > 0) {
    console.error('Учётки E2E, которых не знает зачистка:\n')
    for (const name of missing) {
        console.error(`  ${name} — объявлена в e2e/fixtures/test-accounts.ts`)
    }
    console.error(
        `\nПрогон под такой учёткой оставит её на сервере вместе со всем, что\n` +
            `на неё ссылается, и отчитается об успехе.\n\n` +
            `Добавьте имя в перечень в scripts/e2e-db-snapshot.sh ("for var in ...").`,
    )
    process.exit(1)
}

console.log(`Зачистка покрывает все учётки E2E: ${unique.length}`)
